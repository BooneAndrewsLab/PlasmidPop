/**
 * Special hairpin-loop increments of SantaLucia and Hicks 2004, "The
 * thermodynamics of DNA structural motifs", Annu Rev Biophys Biomol Struct
 * 33:415-440, Supplementary Table S1 ("Free energy (ΔG) and enthalpy (ΔH)
 * increments for tri/tetra loops", kcal/mol in 1 M NaCl at 37 °C). Item 125.
 *
 * Each key is the loop's bases with the closing pair on either end, 5' to 3'
 * (AGAAT: an A·T pair closing the loop GAA). The value is [ΔG, ΔH]; the
 * paper's Equations 8 and 9 (p. 428) add the ΔG to the loop's initiation, and
 * Equation 11 says the Tm uses ΔH "computed with equations analogous to
 * Equations 8-10", so the ΔH is added to the enthalpy. The paper's own
 * examples: CGCAAG is +3.5 - 1.6 - 1.23 (p. 428).
 *
 * Transcribed from the supplement's two lists: 16 triloops (all of the form
 * GNA, N any base, as the paper says) and 115 tetraloops (GNRA, GNAB and the
 * measured sequences). Tetraloops closed by a G·T pair (38 of the 115, such
 * as GAAAAT) are kept as published; the fold only forms Watson-Crick pairs, so
 * it never reaches them. The supplement's Table S2 (multibranch loops) is not
 * used: the fold has no multibranch structures.
 */
